-- PostgreSQL 15+. Fresh database schema for the Stock Market Portfolio Analytics project.
-- Ledger/master relationships use RESTRICT to protect history; watchlist rows are disposable.
CREATE TABLE investors (
 investor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name TEXT NOT NULL,
 email TEXT NOT NULL UNIQUE,
 date_joined DATE NOT NULL DEFAULT CURRENT_DATE,
 risk_profile TEXT NOT NULL CHECK (risk_profile IN ('CONSERVATIVE','MODERATE','AGGRESSIVE'))
);
CREATE TABLE sectors (
 sector_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sector_name TEXT NOT NULL UNIQUE
);
CREATE TABLE stocks (
 stock_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticker_symbol VARCHAR(10) NOT NULL UNIQUE CHECK(ticker_symbol=upper(ticker_symbol)),
 company_name TEXT NOT NULL,
 sector_id BIGINT NOT NULL REFERENCES sectors(sector_id) ON UPDATE CASCADE ON DELETE RESTRICT,
 ipo_date DATE NOT NULL
);
CREATE TABLE stock_prices (
 price_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 stock_id BIGINT NOT NULL REFERENCES stocks(stock_id) ON UPDATE CASCADE ON DELETE RESTRICT,
 price_date DATE NOT NULL,
 open_price NUMERIC(12,4) NOT NULL CHECK(open_price > 0),
 high_price NUMERIC(12,4) NOT NULL CHECK(high_price > 0),
 low_price NUMERIC(12,4) NOT NULL CHECK(low_price > 0),
 close_price NUMERIC(12,4) NOT NULL CHECK(close_price > 0),
 volume BIGINT NOT NULL CHECK(volume >= 0),
 CHECK(high_price >= GREATEST(open_price,low_price,close_price)),
 CHECK(low_price <= LEAST(open_price,high_price,close_price)),
 UNIQUE(stock_id,price_date)
);
CREATE TABLE portfolios (
 portfolio_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 investor_id BIGINT NOT NULL REFERENCES investors(investor_id) ON UPDATE CASCADE ON DELETE RESTRICT,
 portfolio_name TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(investor_id,portfolio_name)
);
CREATE TABLE trades (
 trade_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 portfolio_id BIGINT NOT NULL REFERENCES portfolios(portfolio_id) ON UPDATE CASCADE ON DELETE RESTRICT,
 stock_id BIGINT NOT NULL REFERENCES stocks(stock_id) ON UPDATE CASCADE ON DELETE RESTRICT,
 trade_type TEXT NOT NULL CHECK(trade_type IN ('BUY','SELL')),
 quantity NUMERIC(14,4) NOT NULL CHECK(quantity > 0),
 price_per_share NUMERIC(12,4) NOT NULL CHECK(price_per_share > 0),
 trade_date TIMESTAMPTZ NOT NULL,
 brokerage_fee NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK(brokerage_fee >= 0)
);
-- Current positions are a transaction-maintained cache. Trade history remains canonical.
CREATE TABLE holdings (
 holding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 portfolio_id BIGINT NOT NULL REFERENCES portfolios(portfolio_id) ON UPDATE CASCADE ON DELETE RESTRICT,
 stock_id BIGINT NOT NULL REFERENCES stocks(stock_id) ON UPDATE CASCADE ON DELETE RESTRICT,
 quantity NUMERIC(14,4) NOT NULL CHECK(quantity > 0),
 average_buy_price NUMERIC(12,4) NOT NULL CHECK(average_buy_price > 0),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(portfolio_id,stock_id)
);
CREATE TABLE dividends (
 dividend_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 stock_id BIGINT NOT NULL REFERENCES stocks(stock_id) ON UPDATE CASCADE ON DELETE RESTRICT,
 dividend_date DATE NOT NULL,
 dividend_per_share NUMERIC(10,4) NOT NULL CHECK(dividend_per_share > 0),
 UNIQUE(stock_id,dividend_date)
);
CREATE TABLE watchlists (
 watchlist_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 investor_id BIGINT NOT NULL REFERENCES investors(investor_id) ON UPDATE CASCADE ON DELETE CASCADE,
 stock_id BIGINT NOT NULL REFERENCES stocks(stock_id) ON UPDATE CASCADE ON DELETE CASCADE,
 added_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(investor_id,stock_id)
);
CREATE TABLE cash_transactions (
 transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 portfolio_id BIGINT NOT NULL REFERENCES portfolios(portfolio_id) ON UPDATE CASCADE ON DELETE RESTRICT,
 transaction_type TEXT NOT NULL CHECK(transaction_type IN ('DEPOSIT','WITHDRAWAL','TRADE_BUY','TRADE_SELL','DIVIDEND')),
 amount NUMERIC(14,2) NOT NULL CHECK(amount > 0),
 transaction_date TIMESTAMPTZ NOT NULL DEFAULT now(),
 trade_id BIGINT UNIQUE REFERENCES trades(trade_id) ON UPDATE CASCADE ON DELETE RESTRICT
);
